// An owner of the kind as the setup leaves them: an outdoor listing with the kind and its price (a campground open all year,
// like the test's; the others with their usual season).
async function makeOwner(app, base, kind, n) {
  const OK = require('../outdoor-kinds.js');
  const WK = Object.fromEntries(['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'].map((d) => [d, [['09:00', '17:00']]]));
  const v = app.createVenue({ name: `Outdoor Help Q ${kind} ${n}`, slug: `outdoor-help-q-${kind}-${n}-${++makeSeq}`, region: 'osoyoos', type: 'outdoor', latitude: 49.03 + n / 1000, longitude: -119.46, address: `${n} Lakeshore Dr, Osoyoos`, website: `https://example-${n}.com`, hours: JSON.stringify(WK), description: 'A fixture.' });
  const token = app.createOwnerLink(v.id, {}).url.split('/owner/')[1];
  const season = kind === 'camp' ? null : SEASONS[(OK.K[kind] || {}).season];
  const post = (changes) => fetch(`${base}/owner/${token}/changes?from=setup`, { method: 'POST', headers: { 'Content-Type': 'application/json', Connection: 'close', Origin: base, 'X-Real-IP': `10.78.${n}.1` }, body: JSON.stringify({ changes, from_setup: true, note: '', contact_name: '', contact_email: '', company_website: '', started_at: Date.now() - 60000 }) });
  if (season) { const r0 = await post({ hours: WK, open_months: season }); if (![200, 201].includes(r0.status)) throw new Error(`${kind} season: ${r0.status}`); }
  const r = await post({ indoor_info: { kinds: [kind], length: '1-2h', book: 'busy', age: 'all', ...(season ? { year: 'seasonal' } : {}) }, indoor_price: PRICE[kind] });
  if (![200, 201].includes(r.status)) throw new Error(`${kind}: ${r.status}`);
  return { id: v.id, token };
}

