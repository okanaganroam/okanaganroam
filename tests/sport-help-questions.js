const HELP_SKIP = /^(?:sport-bay-link|sport-kinds-other|sport-green-fees-word|indoor-kinds-many|menu-import|indoor-no-hours|indoor-min-players|indoor-book-party|indoor-local-owned|easy-setup|cuisine-pick|plan-visit|weekly-nights|specials|social-post|indoor-french|french)$/;
const SK = require('../sport-kinds.js');
const CHIP_NAMES = Object.values(SK.SPORT_KIND_LABELS_OWNER).flat().concat(Object.values(SK.SPORT_KIND_WORDS).flat()).sort((a, b) => b.length - a.length);
function foreignIn(main, text, id) {
  if (id && HELP_SKIP.test(id)) return null;
  let t = String(text);
  for (const c of CHIP_NAMES) t = t.split(c).join(' ');
  const mine = new Set(KIND_WORDS[main] || []);
  // A range shares golf's clubs and pros; a simulator its golf words; disc golf its tees and courses.
  const shared = { range: ['golf', 'simgolf'], simgolf: ['golf'], discgolf: [] }[main] || [];
  const words = Object.entries(KIND_WORDS).filter(([k]) => k !== main && !shared.includes(k)).flatMap(([, w]) => w).filter((w) => !mine.has(w)).concat(INDOOR_WORDS);
  const m = new RegExp(`(?<![\\p{L}])(?:${words.join('|')})(?![\\p{L}])`, 'iu').exec(t);
  return m ? `"${m[0]}" …${t.slice(Math.max(0, m.index - 60), m.index + 40)}…` : null;
}
